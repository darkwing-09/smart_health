"""Readiness v2 behaviours (watch extras). Parity with Kotlin is checked via fixtures/readiness_v2.json."""

import json
from dataclasses import replace
from datetime import date, datetime, time, timedelta
from pathlib import Path

from fitagent_agents.data import ActivityDay, Profile, UserContext, WorkoutRecord
from fitagent_agents.metrics import Band, _round, compute_readiness, hrv_score, sleep_quality

TODAY = date(2026, 10, 30)
FIXTURES = Path(__file__).resolve().parents[2] / "fixtures" / "readiness_v2.json"


def ctx(today: ActivityDay | None, *, nights: int = 14, hrv: float | None = 60.0, rhr: int = 58,
        workouts: list[WorkoutRecord] | None = None) -> UserContext:
    days = [ActivityDay(day=TODAY - timedelta(days=i), sleep_minutes=450, resting_hr=rhr, hrv_ms=hrv,
                        hr_min=None) for i in range(nights, 0, -1)]
    days = [replace(d, hrv_ms=(hrv + (i % 3 - 1) * 4) if hrv else None) for i, d in enumerate(days)]
    if today:
        days.append(replace(today, day=TODAY))
    return UserContext(today=TODAY, profile=Profile(), days=days, workouts=workouts or [])


def test_round_is_half_up_like_kotlin():
    assert _round(2.5) == 3 and _round(3.5) == 4 and _round(-0.5) == 0


def test_sleep_quality_rewards_deep_and_rem():
    assert sleep_quality(90, 110, 260, 20) > sleep_quality(20, 40, 360, 60)
    assert sleep_quality(0, 0, 0, 0) == 50


def test_hrv_score_tracks_personal_baseline():
    base = [58, 60, 62, 59, 61, 60, 63]
    assert hrv_score(60, base) > 70
    assert hrv_score(80, base) == 100
    assert hrv_score(40, base) == 0


def test_hrv_needs_seven_nights():
    r = compute_readiness(ctx(ActivityDay(day=TODAY, sleep_minutes=450, hrv_ms=60), nights=5))
    assert "hrv" not in r.components
    r = compute_readiness(ctx(ActivityDay(day=TODAY, sleep_minutes=450, hrv_ms=60), nights=8))
    assert "hrv" in r.components


def test_low_hrv_and_high_rhr_is_a_recovery_day():
    r = compute_readiness(ctx(ActivityDay(day=TODAY, sleep_minutes=380, resting_hr=67, hrv_ms=38)))
    assert r.band is Band.RECOVER
    assert any("HRV" in reason for reason in r.reasons)


def test_stages_add_sleep_quality_component():
    r = compute_readiness(ctx(ActivityDay(day=TODAY, sleep_minutes=450, sleep_deep_min=80, sleep_rem_min=100,
                                          sleep_light_min=250, sleep_awake_min=20)))
    assert "sleep_quality" in r.components


def test_fever_like_signals_cap_the_score():
    r = compute_readiness(ctx(ActivityDay(day=TODAY, sleep_minutes=480, resting_hr=66, hrv_ms=62, skin_temp_delta=1.4)))
    assert r.score <= 45
    assert "fighting something" in r.reasons[0]
    assert all(word not in " ".join(r.reasons).lower() for word in ("fever", "infection", "covid", "ill"))


def test_low_spo2_lowers_nightly_component():
    r = compute_readiness(ctx(ActivityDay(day=TODAY, sleep_minutes=450, spo2_avg=92)))
    assert r.components["nightly"] == 80


def test_very_short_sleep_is_never_push():
    r = compute_readiness(ctx(ActivityDay(day=TODAY, sleep_minutes=200, resting_hr=52, hrv_ms=80)))
    assert r.score <= 55 and r.band is not Band.PUSH


def test_load_spike_is_never_push():
    start = datetime.combine(TODAY, time(7))
    spike = [WorkoutRecord("HIIT", start - timedelta(days=i), 80) for i in range(6)]
    old = [WorkoutRecord("WALK", start - timedelta(days=i), 20) for i in range(10, 28, 4)]
    r = compute_readiness(ctx(ActivityDay(day=TODAY, sleep_minutes=480, resting_hr=55, hrv_ms=70), workouts=spike + old))
    assert r.acwr and r.acwr > 1.5
    assert r.band is not Band.PUSH


def test_shared_fixtures_match():
    """The fixtures were generated by this implementation; this guards against accidental changes."""
    cases = json.loads(FIXTURES.read_text())
    assert len(cases) >= 40
    for case in cases:
        days = [ActivityDay(**{**d, "day": date.fromisoformat(d["day"])}) for d in case["days"]]
        ws = [WorkoutRecord(w["type"], datetime.combine(date.fromisoformat(w["date"]), time(7)), w["minutes"])
              for w in case["workouts"]]
        r = compute_readiness(UserContext(today=date.fromisoformat(case["today"]), profile=Profile(), days=days, workouts=ws))
        assert {"score": r.score, "band": r.band.value, "components": r.components} == case["expected"], case["name"]
